export type TKey = keyof typeof T.en

// ── Context ────────────────────────────────────────────────────────
interface I18nCtx { lang: Lang; setLang: (l: Lang) => void; t: (k: TKey, vars?: Record<string, string>) => string }
const I18nContext = createContext<I18nCtx>({ lang: 'en', setLang: () => {}, t: k => k })

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en')

  useEffect(() => {
    try {
      const s = localStorage.getItem('ds-lang') as Lang | null
      if (s === 'en' || s === 'fr') setLangState(s)
    } catch { /* ignore */ }
  }, [])

  function setLang(l: Lang) {
    setLangState(l)
    try { localStorage.setItem('ds-lang', l) } catch { /* ignore */ }
  }

  function t(k: TKey, vars?: Record<string, string>): string {
    let s = (T[lang][k] ?? T.en[k] ?? k) as string
    if (vars) Object.entries(vars).forEach(([key, val]) => { s = s.replace(`{${key}}`, val) })
    return s
  }

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>
}

export function useT() { return useContext(I18nContext) }

/** Language-independent translate helper — use when you need a specific lang regardless of context */
export function translate(lang: Lang, k: TKey, vars?: Record<string, string>): string {
  let s = (T[lang][k] ?? T.en[k] ?? k) as string
  if (vars) Object.entries(vars).forEach(([key, val]) => { s = s.replace(`{${key}}`, val) })
  return s
}
